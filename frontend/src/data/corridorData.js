/** Convert minutes-from-midnight to HH:MM string */
export function minsToTime(mins) {
  if (mins == null) return '--:--';
  const h = Math.floor(mins / 60) % 24;
  const m = mins % 60;
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}`;
}

